def system_language():
    for key in ("LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"):
        value = os.environ.get(key, "")
        if value:
            locale = value.lower().replace("-", "_")
            if locale.startswith("ru"):
                return "ru"
            if locale.startswith("pt_br"):
                return "pt_BR"
            if locale.startswith("tr"):
                return "tr"
            if locale.startswith("zh"):
                return "zh_CN"
            return "en"
    return "en"


_language = system_language()


def set_language(choice):
    """choice: "ru", "en", "pt_BR", "tr", "zh_CN" or "" (the system's)."""
    global _language
    _language = choice if choice in ("ru", "en", "pt_BR", "tr", "zh_CN") else system_language()


def language():
    return _language


def tr(text):
    if _language == "en":
        return EN.get(text, text)
    if _language == "tr":
        return TR.get(text, EN.get(text, text))
    if _language == "pt_BR":
        # Strings added after the translation fall back to English, not to the Russian key.
        return PT_BR.get(text, EN.get(text, text))
    if _language == "zh_CN":
        return ZH_CN.get(text, EN.get(text, text))
    return text


